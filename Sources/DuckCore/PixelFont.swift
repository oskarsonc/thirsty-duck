/// The bubble's pixel font, from option A of the bubble design. Glyphs are `height` rows with a one pixel gap
/// between them. `#` takes the text color; other letters are the fixed `colors`. Lowercase draws as uppercase.
public enum PixelFont {
    public static let height = 7

    public static let colors: [Character: UInt32] = [
        "B": 0x4DABF7, "L": 0xD0EBFF, "R": 0xE03131, "W": 0xFFFFFF, "K": 0x2B2B2B,
        "Y": 0xFFD43B, "D": 0xFAB005, "P": 0xFF8FA3,
    ]

    static let glyphs: [Character: [String]] = [
        "A": [".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"],
        "B": ["####.", "#...#", "#...#", "####.", "#...#", "#...#", "####."],
        "C": [".###.", "#...#", "#....", "#....", "#....", "#...#", ".###."],
        "D": ["####.", "#...#", "#...#", "#...#", "#...#", "#...#", "####."],
        "E": ["#####", "#....", "#....", "####.", "#....", "#....", "#####"],
        "G": [".###.", "#...#", "#....", "#.###", "#...#", "#...#", ".###."],
        "H": ["#...#", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"],
        "I": ["###", ".#.", ".#.", ".#.", ".#.", ".#.", "###"],
        "K": ["#...#", "#..#.", "#.#..", "##...", "#.#..", "#..#.", "#...#"],
        "L": ["#....", "#....", "#....", "#....", "#....", "#....", "#####"],
        "N": ["#...#", "#...#", "##..#", "#.#.#", "#..##", "#...#", "#...#"],
        "O": [".###.", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."],
        "P": ["####.", "#...#", "#...#", "####.", "#....", "#....", "#...."],
        "Q": [".###.", "#...#", "#...#", "#...#", "#.#.#", "#..#.", ".##.#"],
        "R": ["####.", "#...#", "#...#", "####.", "#.#..", "#..#.", "#...#"],
        "S": [".####", "#....", "#....", ".###.", "....#", "....#", "####."],
        "T": ["#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#.."],
        "U": ["#...#", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."],
        "W": ["#...#", "#...#", "#...#", "#.#.#", "#.#.#", "#.#.#", ".#.#."],
        "Y": ["#...#", "#...#", ".#.#.", "..#..", "..#..", "..#..", "..#.."],
        "!": ["#", "#", "#", "#", "#", ".", "#"],
        "?": [".###.", "#...#", "....#", "...#.", "..#..", ".....", "..#.."],
        ".": [".", ".", ".", ".", ".", ".", "#"],
        "…": [".....", ".....", ".....", ".....", ".....", ".....", "#.#.#"],
        " ": ["..", "..", "..", "..", "..", "..", ".."],
        "💧": ["..B..", "..B..", ".BBB.", ".LBB.", "BLBBB", "BBBBB", ".BBB."],
        "💛": [".......", ".YY.YY.", "YWYYYYD", "YYYYYYD", ".YYYYD.", "..YYD..", "...D..."],
        "💙": [".......", ".BB.BB.", "BLBBBBB", "BBBBBBB", ".BBBBB.", "..BBB..", "...B..."],
        "💪": ["..YY....", ".YYYY...", ".YYD....", ".YD..YY.", ".YD.YYYY", ".YYYYYYD", "..DDDDD."],
        "🥵": [".RRRRR.", "RRRRRRR", "RKRRRKR", "RRRRRRR", "RRKKKRR", "RRKPKRR", ".RRRRR."],
    ]

    public static func glyph(_ c: Character) -> [String]? {
        glyphs[c] ?? c.uppercased().first.flatMap { glyphs[$0] }
    }

    /// Characters without a glyph are skipped.
    public static func width(_ text: String) -> Int {
        let widths = text.compactMap { glyph($0)?[0].count }
        return widths.reduce(0, +) + max(widths.count - 1, 0)
    }
}
